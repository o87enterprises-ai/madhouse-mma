// Magic-byte → extension mapping
function extFromBytes(buf) {
  const b = new Uint8Array(buf.slice(0, 12))
  if (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4E && b[3] === 0x47) return 'png'
  if (b[0] === 0xFF && b[1] === 0xD8 && b[2] === 0xFF) return 'jpg'
  if (b[0] === 0x47 && b[1] === 0x49 && b[2] === 0x46) return 'gif'
  // WebP: RIFF????WEBP
  if (b[0] === 0x52 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x46 &&
      b[8] === 0x57 && b[9] === 0x45 && b[10] === 0x42 && b[11] === 0x50) return 'webp'
  // AVIF: ftyp box at offset 4
  if (b[4] === 0x66 && b[5] === 0x74 && b[6] === 0x79 && b[7] === 0x70) return 'avif'
  return 'bin'
}

function extFromContentType(ct) {
  if (!ct) return null
  if (ct.includes('png'))  return 'png'
  if (ct.includes('webp')) return 'webp'
  if (ct.includes('avif')) return 'avif'
  if (ct.includes('gif'))  return 'gif'
  if (ct.includes('jpeg') || ct.includes('jpg')) return 'jpg'
  return null
}

const mediaMap = {}
const errors = []

for (const [key, path] of Object.entries(ASSETS)) {
  const url = BASE + path
  process.stdout.write(`  Fetching ${key} … `)
  try {
    const res = await fetch(url)
    if (!res.ok) throw new Error(`HTTP ${res.status}`)
    const buf = await res.arrayBuffer()
    const ct = res.headers.get('content-type') || ''
    const ext = extFromContentType(ct) || extFromBytes(buf)
    const filename = `${key}.${ext}`
    writeFileSync(resolve(mediaDir, filename), Buffer.from(buf))
    mediaMap[key] = `/media/${filename}`
    console.log(`→ ${filename} (${(buf.byteLength / 1024).toFixed(0)} KB)`)
  } catch (err) {
    console.log(`FAILED: ${err.message}`)
    errors.push({ key, error: err.message })
    mediaMap[key] = null
  }
}

// Write src/media.js
const mediaJs = [
  '// Auto-generated by scripts/fetch-assets.mjs — do not edit by hand',
  'const media = {',
  ...Object.entries(mediaMap).map(([k, v]) => `  ${k}: ${v ? `'${v}'` : 'null'},`),
  '}',
  'export default media',
].join('\n') + '\n'

writeFileSync(resolve(root, 'src/media.js'), mediaJs)
console.log('\n✓ src/media.js written')

if (errors.length) {
  console.warn('\nFailed assets:')
  errors.forEach(e => console.warn(`  ${e.key}: ${e.error}`))
  console.warn('\nRe-run the script or set those values to null in src/media.js manually.')
}
